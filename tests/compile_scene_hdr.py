"""Rebuild the MIT RenoDX scene shaders; verify embedded bytes unless --write is supplied."""
from pathlib import Path
import argparse
import re
import subprocess

repo = Path(__file__).resolve().parents[1]
root = repo / 'include/xivrender/renodx'
p = argparse.ArgumentParser()
p.add_argument('--fxc', default=r'C:/Program Files (x86)/Windows Kits/10/bin/10.0.26100.0/x64/fxc.exe')
p.add_argument('--write', action='store_true')
args = p.parse_args()
output = repo / 'build/hdr-shaders'
output.mkdir(parents=True, exist_ok=True)
header = '#pragma once\n// Generated by tests/compile_scene_hdr.py; MIT RenoDX shader adaptation.\n'
for name in ('Tonemap_0x85E777EF', 'PostTonemapPreLUT_0xF8F57F0A', 'LUT_0x27EBC404',
             'LUT_0x1F264D17', 'FullscreenGammaCorrection_0xF6E81A1B'):
    target = output / (name + '.cso')
    subprocess.run([args.fxc, '/nologo', '/T', 'ps_5_0', '/E', 'main', '/O3',
                    str(root / (name + '.ps_5_0.hlsl')), '/Fo', str(target)], check=True)
    data = target.read_bytes()
    header += 'inline constexpr unsigned char ' + name + '[] = {\n'
    header += ''.join('    ' + ', '.join(f'0x{x:02x}' for x in data[i:i+16]) + ',\n'
                      for i in range(0, len(data), 16)) + '};\n'
if args.write:
    (root / 'SceneShaders.h').write_text(header, encoding='utf-8')
else:
    pattern = r'0x[0-9a-fA-F]{2}(?=\s*[,}])'
    assert re.findall(pattern, header) == re.findall(pattern, (root / 'SceneShaders.h').read_text()), \
        'Compiled shaders differ; inspect the SDK/compiler version and changes before --write.'
    print('PASS: embedded scene shader bytes match all five maintained HLSL sources')
